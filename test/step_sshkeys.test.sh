#!/bin/sh

# Snippets in single quotes are expanded in the containers, not here.
# shellcheck disable=SC2016

# Tests for the sshkeys step.

# Verification of key types and sizes for all supported types, followed by
# cleaning.
_sshkeys_verify='
    primer_run -s sshkeys install
    assert_equal 0 "$PRIMER_RC"
    assert_match "^256 .* \(ED25519\)$" "$(ssh-keygen -l -f /root/.ssh/id_ed25519.pub)"
    assert_match " \(primer\)$" "$(cat /root/.ssh/id_ed25519.pub)" "marked as generated by primer"
    assert_equal drwx------ "$(stat -c %A /root/.ssh)"
    assert_equal -rw------- "$(stat -c %A /root/.ssh/id_ed25519)"
    primer_run -s sshkeys --sshkeys:type rsa install
    assert_equal 0 "$PRIMER_RC"
    assert_match "^4096 .* \(RSA\)$" "$(ssh-keygen -l -f /root/.ssh/id_rsa.pub)"
    primer_run -s sshkeys --sshkeys:type ecdsa install
    assert_equal 0 "$PRIMER_RC"
    assert_match "^521 .* \(ECDSA\)$" "$(ssh-keygen -l -f /root/.ssh/id_ecdsa.pub)"
    primer_run -s sshkeys --sshkeys:type rsa clean
    assert_equal 0 "$PRIMER_RC"
    assert_false [ -e /root/.ssh/id_rsa ]
    assert_false [ -e /root/.ssh/id_rsa.pub ]
    assert_true [ -f /root/.ssh/id_ed25519 ]
'

test_sshkeys_alpine() {
    in_container "$IMG_ALPINE" "$_sshkeys_verify"
}

test_sshkeys_debian() {
    in_container "$IMG_TRIXIE" "$_sshkeys_verify"
}

# ssh-keygen comes from openssh-client on Ubuntu, openssh-clients on Fedora.
test_sshkeys_ubuntu() {
    in_container "$IMG_UBUNTU" "$_sshkeys_verify"
}

test_sshkeys_fedora() {
    in_container "$IMG_FEDORA" "$_sshkeys_verify"
}

# Existing keys are kept.
test_sshkeys_idempotent() {
    in_container "$IMG_ALPINE" '
        primer_run -s sshkeys install
        assert_equal 0 "$PRIMER_RC"
        before=$(ssh-keygen -l -f /root/.ssh/id_ed25519.pub)
        primer_run -s sshkeys install
        assert_equal 0 "$PRIMER_RC"
        assert_equal "$before" "$(ssh-keygen -l -f /root/.ssh/id_ed25519.pub)"'
}

test_sshkeys_rsa_length() {
    in_container -e PRIMER_STEP_SSHKEYS_RSA_LEN=3072 "$IMG_ALPINE" '
        primer_run -s sshkeys --sshkeys:type rsa install
        assert_equal 0 "$PRIMER_RC"
        assert_match "^3072 " "$(ssh-keygen -l -f /root/.ssh/id_rsa.pub)"'
}

# Keys that existed before are neither replaced nor removed.
test_sshkeys_keeps_existing_keys() {
    in_container "$IMG_ALPINE" '
        apk add -q openssh-keygen >/dev/null
        mkdir -p /root/.ssh && chmod 700 /root/.ssh
        # The marker in the middle of the comment is not the marker.
        ssh-keygen -N "" -t ed25519 -C "my own key (primer) copy" -q -f /root/.ssh/id_ed25519
        before=$(cat /root/.ssh/id_ed25519.pub)
        primer_run -s sshkeys install
        assert_equal 0 "$PRIMER_RC"
        assert_equal "$before" "$(cat /root/.ssh/id_ed25519.pub)"
        primer_run -s sshkeys clean
        assert_equal 0 "$PRIMER_RC"
        assert_contains "/root/.ssh/id_ed25519 was not generated by primer, keeping it" "$PRIMER_ERR"
        assert_true [ -f /root/.ssh/id_ed25519 ]
        assert_equal "$before" "$(cat /root/.ssh/id_ed25519.pub)"'
}
